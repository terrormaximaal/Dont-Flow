/**
 * The line under the wordmark.
 *
 * A tagline has one job on a home screen: to say what the game feels like in
 * the half second before anyone reads the buttons. "MATCH THE COLOUR. KEEP THE
 * COMBO." did not do that - it is a rules summary, it explains a mechanic
 * nobody has met yet, and it would read the same under any game with colours
 * in it.
 *
 * Five were written and four rejected, kept here because the rejected ones are
 * the argument for the one that shipped:
 *
 *   "MATCH THE COLOUR. KEEP THE COMBO."
 *      The old one. Instructions, not an identity.
 *
 *   "BECOME THE COLOUR. HOLD THE LINE."
 *      Better rhythm, but "hold the line" is a war phrase and this game is
 *      about moving between lanes rather than holding one.
 *
 *   "CHANGE COLOUR. DON'T CHANGE LANE."
 *      Accurate and almost witty, and it fights the title: two DON'Ts on one
 *      screen and the joke stops being a joke.
 *
 *   "COLOUR IS SPEED."
 *      Short enough to be a mark, and untrue - colour is safety here, and
 *      speed is the level's own.
 *
 *   "ONE DROP. EVERY COLOUR."   <- shipped
 *      Says the subject, the transformation and the scale in four words, sets
 *      as two balanced halves under a two-line wordmark, and describes the
 *      picture directly above it: a single drop wandering through the whole
 *      palette. It promises a feeling rather than explaining a rule, which is
 *      what a player who has never seen the game needs.
 */
export const TAGLINE = 'ONE DROP. EVERY COLOUR.';
